#include<stdio.h>

int Fact(int iNo)
{
    static int iMult = 1;
    static int i = 1;

    if(i <= iNo)
    {
        iMult = iMult * i;
        i++;
        Fact(iNo);
    }
    return iMult;
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to display factorials.
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue, iRet = 0;

    printf("Enter the number: ");
    scanf("%d",&iValue);

    iRet = Fact(iValue);

    printf("Factorials are : %d\n",iRet);

    return 0;
}

