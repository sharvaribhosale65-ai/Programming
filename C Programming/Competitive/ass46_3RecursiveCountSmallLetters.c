//////////////////////////////////////////////////////////////////////////////////////////
//
//Function name     :   SmallLetters 
//Input             :   int
//Output            :   int
//Description       :   Count small letters from string using recursion.
//Author            :   Sharvari Gorakhnath Bhosale
//Date              :   27.07.2026
//
