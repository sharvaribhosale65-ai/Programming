int SmallLetters(char *str)
{
    static int iCnt = 0;

    if(*str == '\0')
    {
        return iCnt;
    }

    if(*str >= 'a' && *str <= 'z')
    {
        iCnt++;
    }

    SmallLetters(str + 1);

    return iCnt;
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to count small letters from string using recursion.
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iRet = 0;
    char arr[20];

    printf("Enter string: ");
    scanf("%[^\n]", arr);

    iRet = SmallLetters(arr);

    printf("Number of small letters are : %d\n",iRet);

    return 0;
}

