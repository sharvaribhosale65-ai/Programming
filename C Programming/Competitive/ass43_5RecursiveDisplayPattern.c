void Display()
{
    static char i = 'a';

    if(i <= 'f')
    {
        printf("%c\t",i);
        i++;
        Display();
    }
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to display recursive pattern
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    Display();

    return 0;
}

