//////////////////////////////////////////////////////////////////////////////////////////
//
//Function name     :   SmallestDigit 
//Input             :   int
//Output            :   int
//Description       :   Find smallest digit using recursion.
//Author            :   Sharvari Gorakhnath Bhosale
//Date              :   27.07.2026
//
//////////////////////////////////////////////////////////////////////////////////////////

int SmallestDigit(int iNo)
{
    static int iMin = 9;
    int iDigit = 0;

    if(iNo != 0)
    {
        iDigit = iNo % 10;

        if(iDigit < iMin)
        {
            iMin = iDigit;
        }

        SmallestDigit(iNo / 10);
    }
    return iMin;
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to display smallest digit from number
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter the  number : ");
    scanf("%d",&iValue);

    iRet = SmallestDigit(iValue);

    printf("Smallest digit are : %d\n",iRet);

    return 0;
}

