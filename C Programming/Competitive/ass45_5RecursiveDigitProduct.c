#include<stdio.h>

//////////////////////////////////////////////////////////////////////////////////////////
//
//Function name     :   Mult 
//Input             :   int
//Output            :   int
//Description       :   Product of digits using recursion.
//Author            :   Sharvari Gorakhnath Bhosale
//Date              :   27.07.2026
//
//////////////////////////////////////////////////////////////////////////////////////////

int Mult(int iNo)
{
    static int iMult = 1; 
    int iDigit = 0;

    if(iNo != 0)
    {
        iDigit = iNo % 10;
        iMult = iMult * iDigit;
        Mult(iNo / 10);
    }
    return iMult;
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to display product of digits
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter the  number : ");
    scanf("%d",&iValue);

    iRet = Mult(iValue);

    printf("Product of digits are : %d\n",iRet);

    return 0;
}

