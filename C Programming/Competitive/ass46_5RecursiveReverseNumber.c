//////////////////////////////////////////////////////////////////////////////////////////
//
//Function name     :   Reverse 
//Input             :   int
//Output            :   int
//Description       :   Reverse the number using recursion.
//Author            :   Sharvari Gorakhnath Bhosale
//Date              :   27.07.2026
//
//////////////////////////////////////////////////////////////////////////////////////////

int Reverse(int iNo)
{
    static int iRev = 0;
    int iDigit = 0;

    if(iNo != 0)
    {
        iDigit = iNo % 10;
        iRev = (iRev * 10) + iDigit;
        Reverse(iNo / 10);
    }
    return iRev;
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to display reverse number
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter the  number : ");
    scanf("%d",&iValue);

    iRet = Reverse(iValue);

    printf("Reverse number is : %d\n",iRet);

    return 0;
}

