int Sum(int iNo)
{
    static int iSum = 0; 
    int iDigit = 0;

    if(iNo != 0)
    {
        iDigit = iNo % 10;
        iSum = iSum + iDigit;
        Sum(iNo / 10);
    }
    return iSum;
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to display summation of digits
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter the  number : ");
    scanf("%d",&iValue);

    iRet = Sum(iValue);

    printf("Summation of digits are : %d\n",iRet);

    return 0;
}

