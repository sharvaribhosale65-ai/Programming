void Display()
{
    static int i = 5;

    if(i >= 1)
    {
        printf("%d\t",i);
        i--;
        Display();
    }
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to display recursive pattern
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    Display();

    return 0;
}

