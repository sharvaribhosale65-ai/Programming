void Display()
{
    static char i = 'A';

    if(i <= 'F')
    {
        printf("%c\t",i);
        i++;
        Display();
    }
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to display recursive pattern
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    Display();

    return 0;
}

