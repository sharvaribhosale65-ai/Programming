int WhiteSpace(char *str)
{
    static int iCnt = 0;

    if(*str == '\0')
    {
        return iCnt;
    }

    if(*str == ' ')
    {
        iCnt++;
    }

    WhiteSpace(str + 1);

    return iCnt;
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to count white spaces from string using recursion.
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iRet = 0;
    char arr[20];

    printf("Enter string: ");
    scanf("%[^\n]", arr);

    iRet = WhiteSpace(arr);

    printf("Number of white spaces are : %d\n",iRet);

    return 0;
}

