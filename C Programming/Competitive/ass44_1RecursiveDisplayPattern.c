//////////////////////////////////////////////////////////////////////////////////////////
//
//Function name     :   Display 
//Input             :   void
//Output            :   char
//Description       :   Display recursive pattern
//Author            :   Sharvari Gorakhnath Bhosale
//Date              :   27.07.2026
