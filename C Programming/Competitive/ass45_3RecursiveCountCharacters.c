#include<stdio.h>

int Strlen(char *str)
{
    static int iCnt = 0;

    if(*str != '\0')
    {
        iCnt++;
        Strlen(str + 1);
    }

    return iCnt;
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to count characters from string using recursion.
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iRet = 0;
    char arr[20];

    printf("Enter string: ");
    scanf("%s",arr);

    iRet = Strlen(arr);

    printf("Number of characters are : %d\n",iRet);

    return 0;
}

