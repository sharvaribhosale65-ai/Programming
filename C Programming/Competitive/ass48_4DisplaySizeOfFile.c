#include<stdio.h>
#include<stdlib.h>
#include<fcntl.h>
#include<unistd.h>
#include<string.h>
#include<sys/stat.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  User-Defined Macros
//
/////////////////////////////////////////////////////////////////////////////////////////////////

#define BUFFER_SIZE 1024

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function name : DisplaySize
//  Input         : char
//  Output        : int
//  Description   : To display size of file 
//  Date          : 27/07/2026
//  Author        : Sharvari Gorakhnath Bhosale
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int DisplaySize(
                    char Filename[]                 // Parameter to take first input
               )
{
    struct stat sobj;                               // Object of stat structure

    stat(Filename, &sobj);

    return sobj.st_size;
}

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Application to display size of file 
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char Fname[30] = {'\0'};                        // Array to store filename
    int iRet = 0;                                   // Variable to store return value of function

    printf("Enter Filename : ");
    scanf("%s", Fname);

    iRet = DisplaySize(Fname);                      // Function call
    printf("File size is : %d bytes\n", iRet);

    return 0;
}

