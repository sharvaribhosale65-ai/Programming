//////////////////////////////////////////////////////////////////////////////////////////
//
//Function name     :   LargestDigit 
//Input             :   int
//Output            :   int
//Description       :   Find largest digit using recursion.
//Author            :   Sharvari Gorakhnath Bhosale
//Date              :   27.07.2026
//
//////////////////////////////////////////////////////////////////////////////////////////

int LargestDigit(int iNo)
{
    static int iMax = 0;
    int iDigit = 0;

    if(iNo != 0)
    {
        iDigit = iNo % 10;

        if(iDigit > iMax)
        {
            iMax = iDigit;
        }

        LargestDigit(iNo / 10);
    }

    return iMax;
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to display largest digit from number
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter the  number : ");
    scanf("%d",&iValue);

    iRet = LargestDigit(iValue);

    printf("Largest digit are : %d\n",iRet);

    return 0;
}

