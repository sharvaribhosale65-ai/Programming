void Display(int iNo)
{
    static char i = 'a';

    if(iNo >= 1)
    {
        printf("%c\t",i);
        i++;
        Display(iNo-1);
    }
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to display recursive pattern
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter the  number : ");
    scanf("%d",&iValue);

    Display(iValue);

    return 0;
}

