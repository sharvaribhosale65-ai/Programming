void Display(int iNo)
{
    if(iNo >= 1)
    {
        printf("%d\t",iNo);
        iNo--;
        Display(iNo);
    }
}

//////////////////////////////////////////////////////////////////////////////////////////
//
//Application to display recursive pattern
//
//////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter the number : ");
    scanf("%d",&iValue);

    Display(iValue);

    return 0;
}

