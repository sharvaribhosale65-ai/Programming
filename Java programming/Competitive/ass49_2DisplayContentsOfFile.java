import java.util.Scanner;
import java.io.FileInputStream;
import java.io.IOException;

////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Function name : Display
// Input         : void
// Output        : string
// Description   : Display the contents of file on screen
// Date          : 07/08/2026
// Author        : Sharvari Gorakhnath Bhosale
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////

class FileX
{
    public void Display(String fname)
    {
        byte Buffer[] = new byte[1024];
        int iRet = 0;

        try
        {
            FileInputStream fObj = new FileInputStream(fname);

            while((iRet = fObj.read(Buffer)) != -1)
            {
                 System.out.print(new String(Buffer, 0, iRet));
            }
            fObj.close();
        }
        catch(IOException  e)
        {
            System.out.println("Unable to open file.");
        }
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Application to display the contents of file on screen
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////

class ass49_2
{
    public static void main(String[] args) 
    {
        Scanner sObj = new Scanner(System.in);
        FileX fObj = new FileX();

        System.out.println("Enter the filename : ");
        String Filename = sObj.nextLine();

        fObj.Display(Filename);

        sObj.close();
    }
}

